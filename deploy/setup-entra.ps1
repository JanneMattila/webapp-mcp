#Requires -Version 7.0
<#
.SYNOPSIS
    Creates or updates the Microsoft Entra app registration that secures the webapp-mcp server.

.DESCRIPTION
    Idempotent. Safe to re-run, for example after you have registered the SSO client in the
    Teams Developer Portal and need to add its generated Application ID URI.

    Configures:
      * Single-tenant app registration + service principal (enterprise app)
      * Application ID URI api://<clientId> (+ any -AdditionalIdentifierUris)
      * requestedAccessTokenVersion = 2
      * Delegated scope "access_as_user"
      * Web redirect URI https://teams.microsoft.com/api/platform/v1.0/oAuthConsentRedirect
      * Pre-authorized clients:
          - Microsoft Enterprise token store (Microsoft 365 Copilot connectors / plugins)
          - Microsoft Teams desktop/mobile and web
          - Visual Studio Code and Azure CLI (local testing; omit with -SkipDeveloperClients)
      * Microsoft Graph delegated permission User.Read + tenant-wide admin consent (On-Behalf-Of to /me)
      * dotnet user-secrets for local development (TenantId, ClientId, Audiences, optional client secret)

    Writes the results to deploy/entra-app.settings.json, which deploy-appservice.ps1 and
    get-token.ps1 read.

.EXAMPLE
    ./deploy/setup-entra.ps1 -CreateLocalDevSecret

.EXAMPLE
    # After registering the SSO client in the Teams Developer Portal:
    ./deploy/setup-entra.ps1 -AdditionalIdentifierUris "api://auth-00000000-0000-0000-0000-000000000000"
#>
[CmdletBinding()]
param(
    [string] $AppName = "webapp-mcp",

    # Application ID URI(s) generated by the Teams Developer Portal Entra SSO registration.
    [string[]] $AdditionalIdentifierUris = @(),

    # Creates a client secret (90 days) and stores it in dotnet user-secrets so that the
    # On-Behalf-Of flow (get_my_profile) works when running locally. Azure uses a managed identity instead.
    [switch] $CreateLocalDevSecret,

    # Do not pre-authorize Visual Studio Code and Azure CLI (used for local testing only).
    [switch] $SkipDeveloperClients,

    # Do not grant tenant-wide admin consent for Microsoft Graph User.Read.
    [switch] $SkipAdminConsent,

    [string] $ScopeName = "access_as_user",

    [string] $SettingsFile = (Join-Path $PSScriptRoot "entra-app.settings.json")
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$GraphAppId = "00000003-0000-0000-c000-000000000000"
$GraphUserReadScopeId = "e1fd296f-fa3a-4a69-a32f-1b3f0f5d3f0b"
$TeamsConsentRedirectUri = "https://teams.microsoft.com/api/platform/v1.0/oAuthConsentRedirect"
$ProjectPath = Join-Path $PSScriptRoot ".." "src" "webapp-mcp" "webapp-mcp.csproj"

$PreAuthorizedClients = [ordered]@{
    "ab3be6b7-f5df-413d-ac2d-abf1e3fd9c0b" = "Microsoft Enterprise token store"
    "1fec8e78-bce4-4aaf-ab1b-5451cc387264" = "Microsoft Teams desktop/mobile"
    "5e3ce6c0-2b1f-4285-8d4b-75ee78787346" = "Microsoft Teams web"
}
if (-not $SkipDeveloperClients) {
    $PreAuthorizedClients["aebc6443-996d-45c2-90f0-388ff96faa56"] = "Visual Studio Code"
    $PreAuthorizedClients["04b07795-8ddb-461a-bbee-02f9e1bf7b46"] = "Azure CLI"
}

function Invoke-Az {
    $output = & az @args
    if ($LASTEXITCODE -ne 0) {
        throw "Command failed (exit code $LASTEXITCODE): az $($args -join ' ')"
    }
    return $output
}

function Invoke-AzJson {
    $output = Invoke-Az @args
    if ($null -eq $output) { return $null }
    $text = ($output | Out-String).Trim()
    if ([string]::IsNullOrEmpty($text)) { return $null }
    return $text | ConvertFrom-Json -Depth 50
}

function ConvertTo-Array($Value) {
    # @($null) yields a one-element array; filter nulls so JSON bodies don't contain [null].
    # The leading comma stops PowerShell from unrolling the array on return.
    return , @($Value | Where-Object { $null -ne $_ })
}

function Invoke-Graph {
    param(
        [Parameter(Mandatory)] [string] $Method,
        [Parameter(Mandatory)] [string] $Uri,
        [object] $Body,
        [int] $MaxAttempts = 5
    )

    $azArgs = @("rest", "--method", $Method, "--uri", $Uri, "--headers", "Content-Type=application/json", "-o", "json")
    $bodyFile = $null
    try {
        if ($null -ne $Body) {
            $bodyFile = New-TemporaryFile
            $Body | ConvertTo-Json -Depth 50 | Set-Content -Path $bodyFile -Encoding utf8NoBOM
            $azArgs += @("--body", "@$bodyFile")
        }

        # Retry to tolerate Entra replication delays right after objects are created.
        for ($attempt = 1; ; $attempt++) {
            try {
                return Invoke-AzJson @azArgs
            }
            catch {
                if ($attempt -ge $MaxAttempts) { throw }
                Write-Host "  Graph call failed (attempt $attempt/$MaxAttempts), retrying in 10 seconds..." -ForegroundColor DarkYellow
                Start-Sleep -Seconds 10
            }
        }
    }
    finally {
        if ($bodyFile) { Remove-Item $bodyFile -ErrorAction SilentlyContinue }
    }
}

function Get-ODataFilterUri([string] $BaseUri, [string] $Filter) {
    return "$($BaseUri)?`$filter=$([uri]::EscapeDataString($Filter))"
}

function Set-UserSecret([string] $Key, [string] $Value) {
    & dotnet user-secrets set $Key $Value --project $ProjectPath | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "dotnet user-secrets set $Key failed." }
}

# ---------------------------------------------------------------------------
Write-Host "Reading current Azure CLI context..." -ForegroundColor Cyan
$account = Invoke-AzJson account show -o json
$tenantId = $account.tenantId
Write-Host "  Tenant: $tenantId ($($account.user.name))"

# --- App registration -------------------------------------------------------
$apps = Invoke-Graph -Method GET -Uri (Get-ODataFilterUri "https://graph.microsoft.com/v1.0/applications" "displayName eq '$AppName'")
$app = @($apps.value) | Select-Object -First 1
if ($null -eq $app) {
    Write-Host "Creating app registration '$AppName'..." -ForegroundColor Cyan
    $app = Invoke-Graph -Method POST -Uri "https://graph.microsoft.com/v1.0/applications" -Body @{
        displayName    = $AppName
        signInAudience = "AzureADMyOrg"
    }
}
else {
    Write-Host "Updating existing app registration '$AppName' ($($app.appId))..." -ForegroundColor Cyan
}

$clientId = $app.appId
$objectId = $app.id
$app = Invoke-Graph -Method GET -Uri "https://graph.microsoft.com/v1.0/applications/$objectId"

# --- Identifier URIs ---------------------------------------------------------
$identifierUris = [System.Collections.Generic.List[string]]::new()
foreach ($uri in @("api://$clientId") + (ConvertTo-Array $app.identifierUris) + $AdditionalIdentifierUris) {
    if (-not [string]::IsNullOrWhiteSpace($uri) -and -not $identifierUris.Contains($uri.Trim())) {
        $identifierUris.Add($uri.Trim())
    }
}

# --- Scope -------------------------------------------------------------------
$existingScopes = ConvertTo-Array $app.api.oauth2PermissionScopes
$existingPreAuthorized = ConvertTo-Array $app.api.preAuthorizedApplications
$existingScope = $existingScopes | Where-Object { $_.value -eq $ScopeName } | Select-Object -First 1
$scopeId = if ($existingScope) { $existingScope.id } else { [guid]::NewGuid().ToString() }
$scopes = (ConvertTo-Array ($existingScopes | Where-Object { $_.value -ne $ScopeName })) + @(
    [ordered]@{
        id                      = $scopeId
        value                   = $ScopeName
        type                    = "User"
        isEnabled               = $true
        adminConsentDisplayName = "Access $AppName as the signed-in user"
        adminConsentDescription = "Allows the application to access $AppName on behalf of the signed-in user."
        userConsentDisplayName  = "Access $AppName on your behalf"
        userConsentDescription  = "Allows the application to access $AppName on your behalf."
    }
)

# --- Redirect URIs -------------------------------------------------------------
$redirectUris = @((ConvertTo-Array $app.web.redirectUris) + $TeamsConsentRedirectUri | Select-Object -Unique)

# --- Required resource access (Microsoft Graph User.Read) -----------------------
$existingResourceAccess = ConvertTo-Array $app.requiredResourceAccess
$requiredResourceAccess = ConvertTo-Array ($existingResourceAccess | Where-Object { $_.resourceAppId -ne $GraphAppId })
$graphAccess = ConvertTo-Array ($existingResourceAccess | Where-Object { $_.resourceAppId -eq $GraphAppId } | ForEach-Object { $_.resourceAccess })
if (-not ($graphAccess | Where-Object { $_.id -eq $GraphUserReadScopeId })) {
    $graphAccess += [ordered]@{ id = $GraphUserReadScopeId; type = "Scope" }
}
$requiredResourceAccess += [ordered]@{ resourceAppId = $GraphAppId; resourceAccess = @($graphAccess) }

Write-Host "Configuring identifier URIs, scope '$ScopeName', token version 2, redirect URI and Graph User.Read..." -ForegroundColor Cyan
Invoke-Graph -Method PATCH -Uri "https://graph.microsoft.com/v1.0/applications/$objectId" -Body ([ordered]@{
        identifierUris         = @($identifierUris)
        api                    = [ordered]@{
            requestedAccessTokenVersion = 2
            oauth2PermissionScopes      = @($scopes)
            preAuthorizedApplications   = $existingPreAuthorized
        }
        web                    = [ordered]@{ redirectUris = @($redirectUris) }
        requiredResourceAccess = @($requiredResourceAccess)
    }) | Out-Null

# --- Pre-authorized client applications -----------------------------------------
# Done in a separate request because the referenced scope must already exist.
$preAuthorized = ConvertTo-Array ($existingPreAuthorized | Where-Object { -not $PreAuthorizedClients.Contains($_.appId) })
foreach ($clientAppId in $PreAuthorizedClients.Keys) {
    $existing = $existingPreAuthorized | Where-Object { $_.appId -eq $clientAppId } | Select-Object -First 1
    $permissionIds = @((ConvertTo-Array ($existing | ForEach-Object { $_.delegatedPermissionIds })) + $scopeId | Select-Object -Unique)
    $preAuthorized += [ordered]@{ appId = $clientAppId; delegatedPermissionIds = $permissionIds }
    Write-Host "  Pre-authorizing $($PreAuthorizedClients[$clientAppId]) ($clientAppId)"
}

Invoke-Graph -Method PATCH -Uri "https://graph.microsoft.com/v1.0/applications/$objectId" -Body @{
    api = [ordered]@{
        requestedAccessTokenVersion = 2
        oauth2PermissionScopes      = @($scopes)
        preAuthorizedApplications   = @($preAuthorized)
    }
} | Out-Null

# --- Service principal (enterprise application) ------------------------------------
$sps = Invoke-Graph -Method GET -Uri (Get-ODataFilterUri "https://graph.microsoft.com/v1.0/servicePrincipals" "appId eq '$clientId'")
$sp = @($sps.value) | Select-Object -First 1
if ($null -eq $sp) {
    Write-Host "Creating service principal..." -ForegroundColor Cyan
    $sp = Invoke-Graph -Method POST -Uri "https://graph.microsoft.com/v1.0/servicePrincipals" -Body @{ appId = $clientId }
}

# --- Admin consent for Microsoft Graph User.Read ----------------------------------
if (-not $SkipAdminConsent) {
    Write-Host "Granting tenant-wide admin consent for Microsoft Graph User.Read..." -ForegroundColor Cyan
    try {
        $graphSps = Invoke-Graph -Method GET -Uri (Get-ODataFilterUri "https://graph.microsoft.com/v1.0/servicePrincipals" "appId eq '$GraphAppId'")
        $graphSpId = (@($graphSps.value) | Select-Object -First 1).id
        $grants = Invoke-Graph -Method GET -Uri (Get-ODataFilterUri "https://graph.microsoft.com/v1.0/oauth2PermissionGrants" "clientId eq '$($sp.id)' and resourceId eq '$graphSpId' and consentType eq 'AllPrincipals'")
        $grant = @($grants.value) | Select-Object -First 1
        if ($null -eq $grant) {
            Invoke-Graph -Method POST -Uri "https://graph.microsoft.com/v1.0/oauth2PermissionGrants" -Body @{
                clientId    = $sp.id
                consentType = "AllPrincipals"
                resourceId  = $graphSpId
                scope       = "User.Read"
            } | Out-Null
        }
        elseif (($grant.scope -split ' ') -notcontains "User.Read") {
            Invoke-Graph -Method PATCH -Uri "https://graph.microsoft.com/v1.0/oauth2PermissionGrants/$($grant.id)" -Body @{
                scope = "$($grant.scope) User.Read".Trim()
            } | Out-Null
        }
        Write-Host "  Admin consent granted."
    }
    catch {
        Write-Warning "Could not grant admin consent automatically: $($_.Exception.Message)"
        Write-Warning "Ask a Privileged Role / Cloud Application Administrator to grant consent: Entra admin center > App registrations > $AppName > API permissions > Grant admin consent."
    }
}

# --- Local development settings (dotnet user-secrets) --------------------------------
Write-Host "Writing dotnet user-secrets for local development..." -ForegroundColor Cyan
$additionalAudiences = @($identifierUris | Where-Object { $_ -ne "api://$clientId" })
Set-UserSecret "AzureAd:TenantId" $tenantId
Set-UserSecret "AzureAd:ClientId" $clientId
for ($i = 0; $i -lt $additionalAudiences.Count; $i++) {
    Set-UserSecret "AzureAd:Audiences:$i" $additionalAudiences[$i]
}

if ($CreateLocalDevSecret) {
    Write-Host "Creating a 90-day client secret for local On-Behalf-Of testing..." -ForegroundColor Cyan
    $endDate = (Get-Date).ToUniversalTime().AddDays(90).ToString("yyyy-MM-dd")
    $secret = Invoke-Az ad app credential reset --id $clientId --append --display-name "$AppName-local-dev" --end-date $endDate --query password -o tsv
    Set-UserSecret "AzureAd:ClientCredentials:0:SourceType" "ClientSecret"
    Set-UserSecret "AzureAd:ClientCredentials:0:ClientSecret" ($secret | Out-String).Trim()
    Write-Host "  Client secret stored in user-secrets (never committed to source control)."
}

# --- Output -----------------------------------------------------------------------------
$settings = [ordered]@{
    tenantId            = $tenantId
    appName             = $AppName
    clientId            = $clientId
    objectId            = $objectId
    servicePrincipalId  = $sp.id
    scopeName           = $ScopeName
    scope               = "api://$clientId/$ScopeName"
    identifierUris      = @($identifierUris)
    additionalAudiences = $additionalAudiences
}
$settings | ConvertTo-Json -Depth 10 | Set-Content -Path $SettingsFile -Encoding utf8NoBOM

Write-Host ""
Write-Host "Entra app registration is ready." -ForegroundColor Green
Write-Host "  Settings file  : $SettingsFile"
Write-Host "  Tenant ID      : $tenantId"
Write-Host "  Client ID      : $clientId"
Write-Host "  Scope          : api://$clientId/$ScopeName"
Write-Host "  Identifier URIs: $($identifierUris -join ', ')"
Write-Host ""
Write-Host "Next: run ./deploy/deploy-appservice.ps1, then register the SSO client in the Teams Developer Portal (see docs/setup.md)."
