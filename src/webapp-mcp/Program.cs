using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.Identity.Web;
using ModelContextProtocol.AspNetCore;
using ModelContextProtocol.AspNetCore.Authentication;
using WebAppMcp.Tools;

const string McpPolicy = "McpUser";

var builder = WebApplication.CreateBuilder(args);

var azureAd = builder.Configuration.GetSection("AzureAd");
var instance = (azureAd["Instance"] ?? "https://login.microsoftonline.com/").TrimEnd('/');
var tenantId = azureAd["TenantId"];
var clientId = azureAd["ClientId"];
var scope = builder.Configuration["Mcp:Scope"] ?? "access_as_user";

if (string.IsNullOrWhiteSpace(tenantId) || string.IsNullOrWhiteSpace(clientId))
{
    throw new InvalidOperationException(
        "AzureAd:TenantId and AzureAd:ClientId must be configured. " +
        "Run deploy/setup-entra.ps1 (sets user-secrets for local development) or set app settings.");
}

// Delegated (user) authentication: validate Entra ID access tokens and enable
// On-Behalf-Of token acquisition so tools can call Microsoft Graph as the signed-in user.
builder.Services.AddAuthentication(options =>
    {
        options.DefaultAuthenticateScheme = JwtBearerDefaults.AuthenticationScheme;
        options.DefaultChallengeScheme = McpAuthenticationDefaults.AuthenticationScheme;
    })
    .AddMicrosoftIdentityWebApi(builder.Configuration, "AzureAd")
    .EnableTokenAcquisitionToCallDownstreamApi()
    .AddInMemoryTokenCaches();

// MCP authorization spec: 401 challenges include WWW-Authenticate with resource_metadata and
// Protected Resource Metadata (RFC 9728) is served from /.well-known/oauth-protected-resource/mcp.
builder.Services.AddAuthentication()
    .AddMcp(options =>
    {
        options.ResourceMetadata = new()
        {
            ResourceName = "webapp-mcp",
            AuthorizationServers = { $"{instance}/{tenantId}/v2.0" },
            ScopesSupported = [$"api://{clientId}/{scope}"],
        };
    });

// Accept the API's own audiences plus any additional Application ID URIs, e.g. the one
// generated by the Teams Developer Portal Entra SSO registration (AzureAd:Audiences).
builder.Services.PostConfigure<JwtBearerOptions>(JwtBearerDefaults.AuthenticationScheme, options =>
{
    var audiences = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { clientId, $"api://{clientId}" };
    foreach (var audience in azureAd.GetSection("Audiences").Get<string[]>() ?? [])
    {
        if (!string.IsNullOrWhiteSpace(audience))
        {
            audiences.Add(audience.Trim());
        }
    }

    options.TokenValidationParameters.AudienceValidator = null;
    options.TokenValidationParameters.ValidAudience = null;
    options.TokenValidationParameters.ValidAudiences = audiences;
});

builder.Services.AddAuthorizationBuilder()
    .AddPolicy(McpPolicy, policy => policy
        .RequireAuthenticatedUser()
        .RequireScope(scope));

builder.Services.AddHttpContextAccessor();
builder.Services.AddHttpClient(UserProfileTools.GraphClientName, client =>
{
    client.BaseAddress = new Uri("https://graph.microsoft.com/v1.0/");
});

builder.Services.AddMcpServer(options =>
    {
        options.ServerInfo = new() { Name = "webapp-mcp", Version = "1.0.0" };
        options.ServerInstructions =
            "Provides information about the signed-in Microsoft 365 user. " +
            "Use get_my_profile to answer questions about the current user (name, email, job title, office, phone).";
    })
    .WithHttpTransport(options =>
    {
        // Stateless: no session affinity needed, so App Service can scale out.
        options.SessionMode = HttpServerSessionMode.Stateless;
    })
    .WithTools<UserProfileTools>();

var app = builder.Build();

app.UseAuthentication();
app.UseAuthorization();

app.MapGet("/", () => Results.Text("webapp-mcp is running. MCP endpoint: /mcp"));
app.MapMcp("/mcp").RequireAuthorization(McpPolicy);

app.Run();
